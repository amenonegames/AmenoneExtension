using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Amenone.NullObjectGenerator
{
    internal static class NullObjectEmitter
    {
        public static void Emit(SourceProductionContext context, NullObjectTarget target, bool isColliding)
        {
            foreach (var diagnostic in target.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic.ToDiagnostic());
            }

            if (target.Spec is { } spec && !isColliding)
            {
                context.AddSource(spec.HintName, SourceText.From(Render(spec), Encoding.UTF8));
            }
        }

        public static string Render(NullObjectSpec spec)
        {
            var writer = new SourceWriter();
            writer.Line("// <auto-generated/>");
            writer.Line("#nullable disable");
            // CS0612 / CS0618: implementing an obsolete interface or using an obsolete type is the user's choice, not the generated code's.
            // CS0693: a method type parameter may reuse a name of the interface's type parameters, as the interface itself does.
            // CS1591: generated public members carry no XML documentation.
            writer.Line("#pragma warning disable CS0612, CS0618, CS0693, CS1591");
            writer.BlankLine();
            if (spec.Namespace != null)
            {
                writer.Line($"namespace {spec.Namespace}");
                writer.Open();
            }

            WriteType(writer, spec);
            if (spec.Namespace != null)
            {
                writer.Close();
            }

            return writer.ToString();
        }

        private static void WriteType(SourceWriter writer, NullObjectSpec spec)
        {
            var modifiers = spec.IsUnsafe ? $"{spec.Accessibility} unsafe" : spec.Accessibility;
            var baseList = spec.Interfaces.IsEmpty ? string.Empty : " : " + string.Join(", ", spec.Interfaces);
            writer.Line($"{modifiers} class {spec.TypeName}{spec.TypeParameterList}{baseList}");
            WriteConstraints(writer, spec.ConstraintClauses);
            writer.Open();
            var first = true;
            foreach (var member in spec.Members)
            {
                if (!first)
                {
                    writer.BlankLine();
                }

                first = false;
                WriteMember(writer, member, spec.Log);
            }

            writer.Close();
        }

        private static void WriteMember(SourceWriter writer, MemberSpec member, NullObjLog log)
        {
            switch (member)
            {
                case MethodSpec method:
                    WriteMethod(writer, method, log);
                    break;
                case PropertySpec property:
                    WriteProperty(writer, property, log);
                    break;
                case EventSpec eventSpec:
                    WriteEvent(writer, eventSpec, log);
                    break;
            }
        }

        private static void WriteMethod(SourceWriter writer, MethodSpec method, NullObjLog log)
        {
            var parameters = string.Join(", ", method.Parameters);
            writer.Line($"{Prefix(method)}{method.ReturnType} {Qualified(method, method.Name)}{method.TypeParameterList}({parameters})");
            WriteConstraints(writer, method.ConstraintClauses);
            writer.Open();
            foreach (var outParameter in method.OutParameterNames)
            {
                writer.Line($"{outParameter} = default;");
            }

            WriteBody(writer, log, $"{method.LogName} is null. do nothing.", method.ReturnExpression);
            writer.Close();
        }

        private static void WriteProperty(SourceWriter writer, PropertySpec property, NullObjLog log)
        {
            var name = property.Name ?? $"this[{string.Join(", ", property.IndexerParameters)}]";
            writer.Line($"{Prefix(property)}{property.Type} {Qualified(property, name)}");
            writer.Open();
            if (property.HasGetter)
            {
                writer.Line("get");
                writer.Open();
                WriteBody(writer, log, $"{property.LogName} is null. return default value.", property.ReturnExpression);
                writer.Close();
            }

            if (property.Setter != SetterKind.None)
            {
                writer.Line(property.Setter == SetterKind.Init ? "init" : "set");
                writer.Open();
                WriteBody(writer, log, $"{property.LogName} is null. do nothing.", null);
                writer.Close();
            }

            writer.Close();
        }

        private static void WriteEvent(SourceWriter writer, EventSpec eventSpec, NullObjLog log)
        {
            writer.Line($"{Prefix(eventSpec)}event {eventSpec.Type} {Qualified(eventSpec, eventSpec.Name)}");
            writer.Open();
            foreach (var accessor in new[] { "add", "remove" })
            {
                writer.Line(accessor);
                writer.Open();
                WriteBody(writer, log, $"{eventSpec.LogName} is null. do nothing.", null);
                writer.Close();
            }

            writer.Close();
        }

        private static void WriteBody(SourceWriter writer, NullObjLog log, string message, string? returnExpression)
        {
            var literal = SymbolDisplay.FormatLiteral(message, quote: true);
            foreach (var statement in LogStatements(log, literal))
            {
                writer.Line(statement);
            }

            if (returnExpression != null && (log & NullObjLog.ThrowException) == 0)
            {
                writer.Line($"return {returnExpression};");
            }
        }

        private static IEnumerable<string> LogStatements(NullObjLog log, string literal)
        {
            if ((log & NullObjLog.DebugLog) != 0)
            {
                yield return $"global::UnityEngine.Debug.Log({literal});";
            }

            if ((log & NullObjLog.DebugLogErr) != 0)
            {
                yield return $"global::UnityEngine.Debug.LogError({literal});";
            }

            if ((log & NullObjLog.DebugLogWarn) != 0)
            {
                yield return $"global::UnityEngine.Debug.LogWarning({literal});";
            }

            if ((log & NullObjLog.ThrowException) != 0)
            {
                yield return $"throw new global::System.Exception({literal});";
            }
        }

        private static void WriteConstraints(SourceWriter writer, EquatableArray<string> clauses)
        {
            writer.Indent();
            foreach (var clause in clauses)
            {
                writer.Line(clause);
            }

            writer.Unindent();
        }

        private static string Prefix(MemberSpec member) => member.ExplicitInterface is null ? "public " : string.Empty;

        private static string Qualified(MemberSpec member, string name) =>
            member.ExplicitInterface is null ? name : $"{member.ExplicitInterface}.{name}";
    }
}
