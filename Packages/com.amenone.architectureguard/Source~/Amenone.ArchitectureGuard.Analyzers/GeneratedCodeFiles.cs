using System;
using System.IO;
using System.Linq;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Amenone.ArchitectureGuard.Analyzers
{
    // Roslyn が生成コードと見なすファイルの判定（GeneratedCodeUtilities）と同じ規則。SymbolAnalysisContext に判定の API が無いので写している。
    internal static class GeneratedCodeFiles
    {
        private const string GeneratedCodeOption = "generated_code";
        private const string TemporaryGeneratedFilePrefix = "TemporaryGeneratedFile_";

        private static readonly string[] GeneratedFileNameSuffixes = { ".designer", ".generated", ".g", ".g.i" };
        private static readonly string[] AutoGeneratedMarkers = { "<autogenerated", "<auto-generated" };

        public static bool IsGenerated(SyntaxTree tree, AnalyzerOptions options, CancellationToken cancellationToken)
        {
            if (options.AnalyzerConfigOptionsProvider.GetOptions(tree).TryGetValue(GeneratedCodeOption, out var configured)
                && bool.TryParse(configured, out var isGenerated))
            {
                return isGenerated;
            }

            return HasGeneratedFileName(tree.FilePath) || BeginsWithAutoGeneratedComment(tree, cancellationToken);
        }

        private static bool HasGeneratedFileName(string filePath)
        {
            if (string.IsNullOrEmpty(filePath))
            {
                return false;
            }

            var fileName = Path.GetFileName(filePath);
            var nameWithoutExtension = Path.GetFileNameWithoutExtension(fileName);
            return fileName.StartsWith(TemporaryGeneratedFilePrefix, StringComparison.OrdinalIgnoreCase)
                || GeneratedFileNameSuffixes.Any(suffix => nameWithoutExtension.EndsWith(suffix, StringComparison.OrdinalIgnoreCase));
        }

        private static bool BeginsWithAutoGeneratedComment(SyntaxTree tree, CancellationToken cancellationToken) =>
            tree.GetRoot(cancellationToken)
                .GetLeadingTrivia()
                .Where(trivia => trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia))
                .Any(comment => AutoGeneratedMarkers.Any(marker => comment.ToString().IndexOf(marker, StringComparison.OrdinalIgnoreCase) >= 0));
    }
}
